import { test, expect } from './fixtures'
import { LOOP_1, answerQuiz, axeViolations, enterLab, openApp, openMission, readSession, selectView, toggleSwitch, wireByKeyboard } from './helpers'
test.describe('learning UX: onboarding tour, next step, meter, recap', () => {
  test('first-visit tour is skippable by keyboard, remembered across a reload, and reopens from How to play', async ({ page }) => {
    await openApp(page)
    await enterLab(page)
    await openMission(page, 1)
    const tour = page.getByTestId('onboarding-tour')
    await expect(tour).toBeVisible()
    await expect(page.getByTestId('tour-progress')).toContainText('step 1 of 4')
    await expect(tour.getByRole('heading', { name: 'Add parts from the tray' })).toBeFocused()
    expect(await axeViolations(page)).toEqual([])
    // Keyboard only: Tab to Next (Back is disabled), Enter advances.
    await page.keyboard.press('Tab')
    await expect(tour.getByRole('button', { name: 'Next' })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByTestId('tour-progress')).toContainText('step 2 of 4')
    await page.keyboard.press('Escape')
    await expect(tour).toBeHidden()
    await expect(page.getByRole('button', { name: 'How to play' })).toBeFocused()
    expect((await page.evaluate(() => JSON.parse(window.localStorage.getItem('wonderverse:session:v1') ?? '{}'))).settings.tourSeen).toBe(true)
    await page.reload()
    await enterLab(page)
    await openMission(page, 1)
    await expect(tour).toBeHidden()
    await page.getByRole('button', { name: 'How to play' }).click()
    await expect(page.getByTestId('tour-progress')).toContainText('step 1 of 4')
    await page.getByRole('button', { name: 'Skip tour' }).click()
    await expect(tour).toBeHidden()
  })
  test('next-step text follows the report while wiring, and the meter reads a lit lamp in both views', async ({ page, isMobile }) => {
    await openApp(page)
    await enterLab(page)
    await openMission(page, 1)
    await page.getByRole('button', { name: 'Skip tour' }).click()
    await selectView(page, 'schematic')
    const next = page.getByTestId('next-step')
    await expect(next).toContainText('Battery 1 + (positive) is not connected to anything')
    for (const pair of LOOP_1) await wireByKeyboard(page, 'schematic', ...pair)
    await expect(next).toContainText('The loop is complete but Switch 1 is open')
    await toggleSwitch(page, 'schematic', 'Switch 1', 'open') // now closed
    await expect(next).toContainText('Lamp 1 is lit')
    const meter = page.getByRole('combobox', { name: 'Place the meter on a part' })
    await expect(page.getByTestId('meter-panel')).toContainText('Ideal meter in a simplified model')
    await meter.selectOption({ label: 'Lamp 1' })
    const readout = page.getByTestId('meter-readout')
    await expect(readout).toContainText('Lamp 1: 3.00 V across, 499.9 mA through. The simulation says this part is energized.')
    // Same readout in the 3D view (skipped on phones, which default to the schematic).
    if (!(isMobile && page.viewportSize()!.width < 640)) {
      await selectView(page, '3d')
      await expect(readout).toContainText('3.00 V across, 499.9 mA through')
    }
    await toggleSwitch(page, isMobile && page.viewportSize()!.width < 640 ? 'schematic' : '3d', 'Switch 1', 'closed')
    await expect(readout).toContainText('Lamp 1: 0.00 V across, 0.0 mA through')
    await expect(readout).toContainText('Switch is in off position')
    expect(await axeViolations(page)).toEqual([])
  })
  test('the recap lists what was built, measured values, hints and the tested idea, and survives a reload', async ({ page }) => {
    await openApp(page)
    await enterLab(page)
    await openMission(page, 1)
    await page.getByRole('button', { name: 'Skip tour' }).click()
    await selectView(page, 'schematic')
    for (const pair of LOOP_1) await wireByKeyboard(page, 'schematic', ...pair)
    await toggleSwitch(page, 'schematic', 'Switch 1', 'open') // closed
    await toggleSwitch(page, 'schematic', 'Switch 1', 'closed') // open
    await toggleSwitch(page, 'schematic', 'Switch 1', 'open') // closed again: the lamp is lit at completion
    await page.getByRole('button', { name: 'Show a hint' }).click()
    await answerQuiz(page, 'It interrupted the complete path.')
    await page.getByRole('button', { name: 'Finish mission' }).click()
    const dialog = page.getByRole('dialog', { name: /Mission complete: Complete the Loop/ })
    await expect(dialog.getByTestId('recap-counts')).toContainText('1 battery, 1 switch, 1 lamp, 3 wires')
    await expect(dialog.getByTestId('recap-readings')).toContainText('Lamp 1: 3.00 V across, 499.9 mA through (energized)')
    await expect(dialog.getByTestId('recap-hints')).toHaveText('1 of 3')
    await expect(dialog.getByTestId('recap-misconception')).toContainText('Opening a switch uses up the electricity')
    await expect(dialog).toContainText('Try next: Mission 2: Fix the Fault')
    expect(await axeViolations(page)).toEqual([])
    const saved = (await readSession(page)) as unknown as { recaps: Record<string, { hintsUsed: number; wires: number }> }
    expect(saved.recaps['mission-1']).toMatchObject({ hintsUsed: 1, wires: 3 })
    await page.reload()
    await enterLab(page)
    await page.getByRole('button', { name: 'Review Mission 1' }).click()
    await expect(page.getByRole('dialog').getByTestId('recap-readings')).toContainText('(energized)')
    await expect(page.getByRole('dialog').getByTestId('recap-hints')).toHaveText('1 of 3')
  })
})
